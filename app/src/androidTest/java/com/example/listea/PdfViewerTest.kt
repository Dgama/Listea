import android.content.ClipboardManager
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.test.getBoundsInRoot
import androidx.compose.ui.test.junit4.createComposeRule
import androidx.compose.ui.test.onAllNodesWithTag
import androidx.compose.ui.test.onNodeWithTag
import androidx.compose.ui.test.onNodeWithText
import androidx.compose.ui.test.performClick
import androidx.compose.ui.test.performTouchInput
import androidx.compose.ui.test.pinch
import androidx.compose.ui.test.swipe
import androidx.compose.ui.unit.dp
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

/**
 * The PDF viewer as a product: pages render, a vertical drag scrolls them, a pinch zooms, a
 * horizontal swipe turns the page, a scan offers nothing to select, and Copy copies.
 *
 * **These are the gestures adb cannot inject.** A scroll, a pinch and an edge swipe are exactly the
 * three things a device walk has to approximate and a screenshot cannot prove, so they run here on
 * the real renderer, on this phone, and the device walk then checks the surrounded screen.
 *
 * Fixtures are generated by [PdfFixtureFactory] (see its KDoc for why none are committed); the real
 * three-page document in `androidTest/assets` is opened too, because a generated file and a
 * produced file do not fail the same way.
 */
@RunWith(AndroidJUnit4::class)
class PdfViewerTest {

    @get:Rule
    val rule = createComposeRule()

    @Test
    fun everyGeneratedFixtureOpensAndItsTextLayerIsReadable() = runBlocking {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val expected = listOf(
            PdfFixtureFactory.prose(context) to 2,
            PdfFixtureFactory.scanned(context) to 2,
            PdfFixtureFactory.twoColumn(context) to 1,
            PdfFixtureFactory.hebrew(context) to 1
        )

        for ((fixture, pageCount) in expected) {
            val state = PdfFixtureFactory.openReader(fixture)
            try {
                assertNull("${fixture.name}: the renderer failed to open it", state.error)
                assertEquals("${fixture.name}: page count", pageCount, state.pageCount)
                assertNotNull("${fixture.name}: page 1 has no text layer", state.readPageText(0))
            } finally {
                state.dispose()
            }
        }

        // The text fixtures are asserted word for word; this is the check the generator exists to
        // pass. A font the extractor cannot map would leave an empty page and no failure otherwise.
        val prose = PdfFixtureFactory.prose(context)
        val proseState = PdfFixtureFactory.openReader(prose)
        try {
            val text = PdfReadingOrder.of(proseState.readPageText(0)!!)
            assertEquals(
                "${PdfFixtureFactory.FirstWord}\n${PdfFixtureFactory.SecondWord}",
                text.text(0, text.size - 1)
            )
        } finally {
            proseState.dispose()
        }
    }

    @Test
    fun aVerticalDragScrollsThePagesAndAPinchZoomsTheDocument() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val fixture = assetFixture(context, "pdf-spike.pdf")
        lateinit var zoom: MediaZoomState
        rule.showPdf(fixture, onZoom = { zoom = it })
        rule.awaitSelectionLayer(0)

        val layer = rule.onNodeWithTag("pdf-selection-0")
        val before = layer.getBoundsInRoot()

        rule.onNodeWithTag("card").performTouchInput {
            swipe(center, center - Offset(0f, 240.dp.toPx()), durationMillis = 300)
        }
        rule.waitForIdle()

        val after = layer.getBoundsInRoot()
        assertTrue(
            "a vertical drag should scroll the page list: $before -> $after",
            after.top < before.top - 1.dp
        )

        rule.onNodeWithTag("card").performTouchInput {
            pinch(
                start0 = Offset(center.x - 40f, center.y),
                end0 = Offset(center.x - 240f, center.y),
                start1 = Offset(center.x + 40f, center.y),
                end1 = Offset(center.x + 240f, center.y)
            )
        }
        rule.waitForIdle()
        assertTrue("a pinch should zoom the document: scale=${zoom.scale}", zoom.scale > 1f)
    }

    @Test
    fun aHorizontalSwipeToTheLeftStepsForward() {
        // Each direction gets its own test: a committed swipe animates its content off screen, so
        // the second direction would be measured on a card that had already left the stage.
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val fixture = assetFixture(context, "pdf-spike.pdf")

        var forward = 0
        rule.showPdf(
            fixture,
            canSwipeForward = true,
            onSwipeForward = { forward++ }
        )
        rule.awaitSelectionLayer(0)
        rule.onNodeWithTag("card").performTouchInput {
            swipe(Offset(width * 0.8f, centerY), Offset(width * 0.2f, centerY), 300)
        }
        rule.waitUntil(5_000) { forward == 1 }
        assertEquals("a leftward swipe should step forward once", 1, forward)
    }

    @Test
    fun aHorizontalSwipeToTheRightStepsBack() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val fixture = assetFixture(context, "pdf-spike.pdf")

        var back = 0
        rule.showPdf(
            fixture,
            canSwipeBack = true,
            onSwipeBack = { back++ }
        )
        rule.awaitSelectionLayer(0)
        rule.onNodeWithTag("card").performTouchInput {
            swipe(Offset(width * 0.2f, centerY), Offset(width * 0.8f, centerY), 300)
        }
        rule.waitUntil(5_000) { back == 1 }
        assertEquals("a rightward swipe should step back once", 1, back)
    }

    @Test
    fun aScannedPageRendersAndOffersNothingToSelect() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val fixture = PdfFixtureFactory.scanned(context)

        // The renderer really has no text: the UI assertion below is not passing by accident of a
        // page that simply had not loaded yet.
        runBlocking {
            val state = PdfFixtureFactory.openReader(fixture)
            try {
                assertTrue("a scanned page must have no glyphs", state.readPageText(0)!!.isEmpty)
                assertTrue("a scanned page must have no glyphs", state.readPageText(1)!!.isEmpty)
            } finally {
                state.dispose()
            }
        }

        rule.showPdf(fixture)
        rule.waitUntil(10_000) {
            rule.onAllNodesWithTag("pdf-page-0").fetchSemanticsNodes().isNotEmpty()
        }
        rule.waitForIdle()
        // No waiting-for-absence is needed: the layer is installed only when the page's text is
        // non-empty, and this page's text is empty in every state — pending or loaded — so time
        // could never make a layer appear. Absence here is a complete answer, not a race.
        assertFalse(
            "a page without text must not offer selection",
            rule.onAllNodesWithTag("pdf-selection-0").fetchSemanticsNodes().isNotEmpty()
        )
    }

    @Test
    fun aSelectedPassageIsCopiedToTheClipboard() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val fixture = PdfFixtureFactory.prose(context)
        var quote: PdfQuote? = null
        rule.showPdf(fixture, onQuote = { quote = it })
        rule.awaitSelectionLayer(0)

        rule.onNodeWithTag("pdf-selection-0").performTouchInput {
            down(Offset(width * 0.10f, height * 0.065f))
            advanceEventTime(700)
            up()
        }
        rule.waitForIdle()

        val selected = quote
        assertNotNull("a long press should select the word under it", selected)
        assertEquals(PdfFixtureFactory.FirstWord, selected!!.quote)

        rule.onNodeWithText("Copy").performClick()
        rule.waitForIdle()

        val clipboard = context.getSystemService(ClipboardManager::class.java)
        val copied = clipboard.primaryClip?.getItemAt(0)?.text?.toString()
        assertEquals("Copy should put the quote on the clipboard", selected.quote, copied)
    }

    // --- fixture ---------------------------------------------------------------------------------

    private fun assetFixture(context: android.content.Context, asset: String): PdfFixture {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        val dir = java.io.File(context.cacheDir, "shared").apply { mkdirs() }
        val file = java.io.File(dir, asset)
        instrumentation.context.assets.open(asset).use { input ->
            file.outputStream().use { output -> input.copyTo(output) }
        }
        val uri = androidx.core.content.FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            file
        )
        return PdfFixture(file, uri)
    }
}
